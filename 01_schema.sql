-- =============================================================================
-- Dairy Management System - MySQL 8 schema (01_schema.sql)
-- Conventions: see CONTRACT section 1.
--   * Tables: singular PascalCase, PK = <Table>Id BIGINT AUTO_INCREMENT.
--   * Common columns: CreatedBy, CreatedDate, ModifiedBy, ModifiedDate, IsActive
--     (pure log/ledger tables keep only CreatedBy/CreatedDate or their own timestamps).
--   * Money DECIMAL(14,2); rates/prices DECIMAL(12,4); quantities DECIMAL(12,3); FAT/SNF/CLR DECIMAL(5,2).
--   * Status columns are VARCHAR; allowed values are documented in the column COMMENT.
--   * CreatedBy/ModifiedBy/ApprovedBy/... "who" columns are plain BIGINT user ids (no FK to User).
--   * FK_<Table>_<Col> / IX_<Table>_<Cols> / UQ_<Table>_<Cols> naming. Every FK column is indexed.
--   * Always quote table names with backticks (`User`, `Route`).
--   * Sequence numbers (FarmerCode, InvoiceNumber, ...) are generated by procedures using
--     SystemSetting keys (no extra table).
--   * Shift open/close is not stored: CollectionShift is master data; shift dashboards aggregate
--     MilkCollection by (CollectionDate, ShiftId, CollectionCenterId).
-- =============================================================================

